-- Nhật ký thao tác của quản trị viên: ai, lúc nào, làm gì, với tài khoản / dữ liệu nào.
-- Ghi email dạng ảnh chụp (không khóa ngoại tới app_user) để dòng nhật ký giữ nguyên khi tài khoản đổi email.
CREATE TABLE admin_audit (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    actor_id     BIGINT                   NOT NULL,
    actor_email  VARCHAR(160)             NOT NULL,
    action       VARCHAR(32)              NOT NULL,
    target_id    BIGINT,
    target_email VARCHAR(160),
    detail       VARCHAR(300),
    CONSTRAINT ck_admin_audit_action CHECK (action IN
        ('USER_LOCK', 'USER_UNLOCK', 'ROLE_CHANGE', 'SESSIONS_REVOKE', 'DATA_IMPORT', 'EMAIL_DISPATCH'))
);
CREATE INDEX ix_admin_audit_created ON admin_audit (created_at);
