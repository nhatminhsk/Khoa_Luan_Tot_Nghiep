-- Bậc lãi suất theo số tiền gửi (biểu chính thức của từng ngân hàng), nạp từ deposit_rate_tiers.csv.
-- deposit_rate giữ bậc thấp nhất để so sánh 22 ngân hàng cùng một bậc; trang gửi tiết kiệm dùng thêm bảng này
-- để tính lãi đúng theo số tiền người dùng nhập. Một dòng = một bậc trên bậc thấp nhất (min_amount_vnd > 0).
-- base_rate_percent: lãi bậc thấp nhất lúc đối chiếu biểu; chỉ áp bậc khi deposit_rate ngày mới nhất còn bằng số này.
CREATE TABLE deposit_rate_tier (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker            VARCHAR(8)    NOT NULL REFERENCES bank (ticker),
    term_months       INTEGER       NOT NULL,
    channel           VARCHAR(8)    NOT NULL,
    min_amount_vnd    BIGINT        NOT NULL,
    rate_percent      NUMERIC(7, 4) NOT NULL,
    base_rate_percent NUMERIC(7, 4) NOT NULL,
    tier_label        VARCHAR(60)   NOT NULL,
    valid_from        DATE,
    source            VARCHAR(500),
    CONSTRAINT uq_deposit_rate_tier UNIQUE (ticker, term_months, channel, min_amount_vnd)
);
CREATE INDEX ix_deposit_rate_tier_term ON deposit_rate_tier (term_months, channel);
