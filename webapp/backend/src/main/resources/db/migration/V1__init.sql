-- Schema khởi tạo. Viết theo cú pháp chung của H2 (chế độ PostgreSQL) và PostgreSQL.
--
-- Nhóm 1: dữ liệu dùng chung, nạp từ data/serving/*.csv (DataImportService). Người dùng chỉ đọc.
-- Nhóm 2: kết quả thuật toán (xếp hạng, dự báo, khía cạnh review). Rỗng cho tới khi pipeline ghi file.
-- Nhóm 3: dữ liệu riêng từng người dùng (4 bảng theo scope): tài khoản, nhu cầu, theo dõi, thông báo.

-- ===== Nhóm 1: dữ liệu dùng chung =====

CREATE TABLE bank (
    ticker      VARCHAR(8)   PRIMARY KEY,
    short_name  VARCHAR(64)  NOT NULL,
    full_name   VARCHAR(160) NOT NULL,
    app_name    VARCHAR(120)
);

CREATE TABLE indicator (
    code          VARCHAR(40)  PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    camels_group  VARCHAR(2)   NOT NULL,
    unit          VARCHAR(16)  NOT NULL,
    direction     VARCHAR(16)  NOT NULL,
    description   VARCHAR(400),
    display_order INTEGER      NOT NULL
);

CREATE TABLE bank_quarter_value (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker         VARCHAR(8)       NOT NULL REFERENCES bank (ticker),
    period         VARCHAR(7)       NOT NULL,
    period_end     DATE             NOT NULL,
    indicator_code VARCHAR(40)      NOT NULL REFERENCES indicator (code),
    val            DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_bank_quarter_value UNIQUE (ticker, indicator_code, period)
);
CREATE INDEX ix_bank_quarter_value_indicator ON bank_quarter_value (indicator_code, period);

CREATE TABLE deposit_rate (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_date    DATE          NOT NULL,
    ticker       VARCHAR(8)    NOT NULL REFERENCES bank (ticker),
    term_months  INTEGER       NOT NULL,
    channel      VARCHAR(8)    NOT NULL,
    rate_percent NUMERIC(7, 4) NOT NULL,
    source       VARCHAR(40),
    CONSTRAINT uq_deposit_rate UNIQUE (rate_date, ticker, term_months, channel)
);
CREATE INDEX ix_deposit_rate_term ON deposit_rate (term_months, channel, rate_date);
CREATE INDEX ix_deposit_rate_bank ON deposit_rate (ticker, rate_date);

CREATE TABLE lending_rate (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rate_month          VARCHAR(7)    NOT NULL,
    ticker              VARCHAR(8)    NOT NULL REFERENCES bank (ticker),
    lending_avg_percent NUMERIC(7, 4) NOT NULL,
    deposit_avg_percent NUMERIC(7, 4),
    source_url          VARCHAR(500),
    CONSTRAINT uq_lending_rate UNIQUE (rate_month, ticker)
);

CREATE TABLE app_store_snapshot (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker        VARCHAR(8)       NOT NULL REFERENCES bank (ticker),
    store         VARCHAR(16)      NOT NULL,
    snapshot_date DATE             NOT NULL,
    app_name      VARCHAR(120),
    score         DOUBLE PRECISION,
    ratings       BIGINT,
    CONSTRAINT uq_app_store_snapshot UNIQUE (ticker, store)
);

CREATE TABLE app_review_monthly (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker      VARCHAR(8)       NOT NULL REFERENCES bank (ticker),
    review_month VARCHAR(7)      NOT NULL,
    n_reviews   INTEGER          NOT NULL,
    mean_score  DOUBLE PRECISION,
    pct_1star   DOUBLE PRECISION,
    pct_5star   DOUBLE PRECISION,
    usable      BOOLEAN          NOT NULL,
    CONSTRAINT uq_app_review_monthly UNIQUE (ticker, review_month)
);

CREATE TABLE policy_program (
    code     VARCHAR(40)  PRIMARY KEY,
    name     VARCHAR(200) NOT NULL,
    category VARCHAR(20)  NOT NULL
);

CREATE TABLE program_participation (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code VARCHAR(40)  NOT NULL REFERENCES policy_program (code),
    ticker       VARCHAR(8)   NOT NULL REFERENCES bank (ticker),
    participates BOOLEAN      NOT NULL,
    list_as_of   DATE,
    source_url   VARCHAR(500),
    CONSTRAINT uq_program_participation UNIQUE (program_code, ticker)
);

CREATE TABLE program_rate (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_code   VARCHAR(40)   NOT NULL REFERENCES policy_program (code),
    borrower_group VARCHAR(120)  NOT NULL,
    valid_from     DATE,
    valid_to       DATE,
    rate_percent   NUMERIC(7, 4),
    spread_min     NUMERIC(7, 4),
    spread_max     NUMERIC(7, 4),
    source_url     VARCHAR(500)
);

CREATE TABLE dataset_info (
    dataset       VARCHAR(40)  PRIMARY KEY,
    name          VARCHAR(120) NOT NULL,
    source        VARCHAR(200),
    frequency     VARCHAR(16)  NOT NULL,
    last_updated  VARCHAR(10),
    row_count     INTEGER,
    coverage_note VARCHAR(300)
);

-- ===== Nhóm 2: kết quả thuật toán =====

CREATE TABLE ranking_result (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    as_of_period   VARCHAR(7)       NOT NULL,
    purpose        VARCHAR(8)       NOT NULL,
    ticker         VARCHAR(8)       NOT NULL REFERENCES bank (ticker),
    rank_value     INTEGER          NOT NULL,
    rank_low       INTEGER,
    rank_high      INTEGER,
    score          DOUBLE PRECISION,
    group_label    VARCHAR(80),
    top_positive   VARCHAR(40),
    top_negative   VARCHAR(40),
    method_version VARCHAR(40),
    CONSTRAINT uq_ranking_result UNIQUE (purpose, as_of_period, ticker)
);

CREATE TABLE forecast_point (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker         VARCHAR(8)       NOT NULL REFERENCES bank (ticker),
    indicator_code VARCHAR(40)      NOT NULL REFERENCES indicator (code),
    origin_period  VARCHAR(7)       NOT NULL,
    target_period  VARCHAR(7)       NOT NULL,
    horizon        INTEGER          NOT NULL,
    val            DOUBLE PRECISION NOT NULL,
    lower_bound    DOUBLE PRECISION,
    upper_bound    DOUBLE PRECISION,
    naive_value    DOUBLE PRECISION,
    method         VARCHAR(60),
    CONSTRAINT uq_forecast_point UNIQUE (ticker, indicator_code, origin_period, horizon)
);

CREATE TABLE app_aspect_score (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker    VARCHAR(8)       NOT NULL REFERENCES bank (ticker),
    period    VARCHAR(7)       NOT NULL,
    aspect    VARCHAR(24)      NOT NULL,
    score     DOUBLE PRECISION NOT NULL,
    n_reviews INTEGER          NOT NULL,
    CONSTRAINT uq_app_aspect_score UNIQUE (ticker, period, aspect)
);

-- Nhật ký nạp dữ liệu: checksum để chỉ nạp lại file đã đổi.
CREATE TABLE import_run (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset     VARCHAR(40)              NOT NULL,
    file_name   VARCHAR(120)             NOT NULL,
    checksum    VARCHAR(64),
    row_count   INTEGER,
    status      VARCHAR(12)              NOT NULL,
    message     VARCHAR(1000),
    started_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_import_run_dataset ON import_run (dataset, started_at);

-- ===== Nhóm 3: dữ liệu riêng từng người dùng =====

-- Tài khoản + cài đặt thông báo (gộp vào một bảng vì là quan hệ 1-1).
CREATE TABLE app_user (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email              VARCHAR(160)             NOT NULL,
    password_hash      VARCHAR(100)             NOT NULL,
    display_name       VARCHAR(80)              NOT NULL,
    role               VARCHAR(12)              NOT NULL,
    notify_rate_change BOOLEAN                  NOT NULL DEFAULT TRUE,
    notify_new_ranking BOOLEAN                  NOT NULL DEFAULT TRUE,
    notify_channel     VARCHAR(12)              NOT NULL DEFAULT 'IN_APP',
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_app_user_email UNIQUE (email)
);

-- Nhu cầu và trọng số đã lưu. Không lưu dữ liệu tài chính cá nhân (thu nhập, số dư, khoản vay đang có).
CREATE TABLE saved_need (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT                   NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    purpose       VARCHAR(8)               NOT NULL,
    label         VARCHAR(80)              NOT NULL,
    amount        BIGINT                   NOT NULL,
    term_months   INTEGER                  NOT NULL,
    channel       VARCHAR(8),
    loan_purpose  VARCHAR(20),
    repayment     VARCHAR(12),
    weight_rate   INTEGER,
    weight_safety INTEGER,
    weight_app    INTEGER,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_saved_need_user ON saved_need (user_id);

CREATE TABLE watch_item (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT                   NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    ticker         VARCHAR(8)               NOT NULL REFERENCES bank (ticker),
    rate_threshold NUMERIC(5, 2)            NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_watch_item UNIQUE (user_id, ticker)
);

-- ref_key chống tạo trùng thông báo khi nạp lại cùng một file (ví dụ "RATE:VCB:2026-09-27").
CREATE TABLE notification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT                   NOT NULL REFERENCES app_user (id) ON DELETE CASCADE,
    type       VARCHAR(16)              NOT NULL,
    ticker     VARCHAR(8),
    title      VARCHAR(160)             NOT NULL,
    body       VARCHAR(1000)            NOT NULL,
    ref_key    VARCHAR(80)              NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_notification_ref UNIQUE (user_id, ref_key)
);
CREATE INDEX ix_notification_user ON notification (user_id, created_at);
